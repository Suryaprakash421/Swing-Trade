#!/usr/bin/env sh
# Run from host cron. Uses the database container's pg_dump, never an exposed DB port.
set -eu
umask 077
repo_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
backup_dir=${BACKUP_DIR:-"$repo_dir/backups"}
mkdir -p "$backup_dir"
chmod 700 "$backup_dir"
archive="$backup_dir/paperlane-$(date -u +%Y%m%dT%H%M%SZ)-$$.dump"
temporary="$archive.partial"
trap 'rm -f "$temporary"' EXIT HUP INT TERM
docker compose --project-directory "$repo_dir" exec -T db sh -c \
  'pg_dump --format=custom --no-owner -U "$POSTGRES_USER" -d "$POSTGRES_DB"' > "$temporary"
test -s "$temporary"
docker compose --project-directory "$repo_dir" exec -T db pg_restore --list < "$temporary" > /dev/null
mv "$temporary" "$archive"
# Retain approximately 14 days, deleting only archives generated by this script.
find "$backup_dir" -type f -name 'paperlane-*.dump' -mtime +13 -delete
printf 'Backup created: %s\n' "$archive"
